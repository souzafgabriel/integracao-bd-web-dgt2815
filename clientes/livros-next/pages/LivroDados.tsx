import { Menu } from '@/componentes/Menu';
import type { NextPage } from 'next';
import Head from 'next/head';
import React, { useState } from 'react';
import styles from '../styles/Home.module.css';
import _controleEditora from '../classes/controle/ControleEditora';
import ControleLivros from '../classes/controle/ControleLivros';
import Livro from '@/classes/modelo/Livro';
import Router from 'next/router';

const controleEditora = new _controleEditora();
const controleLivros = new ControleLivros();

const LivroDados: NextPage = () => {
    const opcoes = controleEditora.getEditoras().map((editora) => {
        return { value: editora.codEditora, text: editora.nome };
    });

    const [titulo, setTitulo] = useState('');
    const [resumo, setResumo] = useState('');
    const [autores, setAutores] = useState('');
    const [codEditora, setCodEditora] = useState(opcoes[0]?.value ?? 1);

    const tratarCombo = function (evento: any) {
        setCodEditora(Number(evento.target.value));
    };

    const incluir = function (evento: any) {
        evento.preventDefault();
        const novoLivro = new Livro(
            '',
            Number(codEditora),
            titulo,
            resumo,
            autores.split('\n')
        );
        controleLivros.incluir(novoLivro).then(() => {
            Router.push('/LivroLista');
        });
    };

    return (
        <div className={styles.container}>
            <Head>
                <title>Loja Next</title>
                <meta name="description" content="Generated by create next app" />
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <Menu />
            <h1 className={styles.title}>Novo Livro</h1>
            <main className={styles.main}>
                <form onSubmit={incluir}>
                    <div className="form-group mb-3">
                        <label htmlFor="titulo">Título</label>
                        <input
                            onChange={(e) => setTitulo(e.target.value)}
                            type="text"
                            className="form-control"
                            id="titulo"
                            placeholder="Título"
                            required
                        />
                    </div>

                    <div className="form-group mb-3">
                        <label htmlFor="resumo">Resumo</label>
                        <textarea
                            onChange={(e: any) => setResumo(e.target.value)}
                            className="form-control"
                            id="resumo"
                            placeholder="Resumo"
                            rows={3}
                            required
                        />
                    </div>

                    <div className="form-group mb-3">
                        <label htmlFor="editora">Editora</label>
                        <select
                            className="form-control"
                            id="editora"
                            value={codEditora}
                            onChange={tratarCombo}
                        >
                            {opcoes.map((e) => {
                                return <option key={e.value} value={e.value}>{e.text}</option>;
                            })}
                        </select>
                    </div>

                    <div className="form-group mb-3">
                        <label htmlFor="autores">Autores (1 por linha)</label>
                        <textarea
                            onChange={(e) => setAutores(e.target.value)}
                            className="form-control"
                            id="autores"
                            placeholder="Autores"
                            rows={3}
                            required
                        />
                    </div>

                    <button type="submit" className="btn btn-primary">Salvar dados</button>
                </form>
            </main>
        </div>
    );
};

export default LivroDados;
